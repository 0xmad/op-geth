// Log represents a contract log event. These events are generated by the LOG opcode and
// stored/indexed by the node.
type Log struct {
	// Consensus fields:
	// address of the contract that generated the event
	Address common.Address `json:"address" gencodec:"required"`
	// Address32 is the logger when an address32 account emitted this log.
	// Nil for an address20 logger. The RLP address is then 32 bytes.
	Address32 *common.Address32 `json:"-" rlp:"-"`
	// list of topics provided by the contract.
	Topics []common.Hash `json:"topics" gencodec:"required"`
	// supplied by the contract, usually ABI-encoded
	Data []byte `json:"data" gencodec:"required"`

	// Derived fields. These fields are filled in by the node
	// but not secured by consensus.
	// block in which the transaction was included
	BlockNumber uint64 `json:"blockNumber" rlp:"-"`
	// hash of the transaction
	TxHash common.Hash `json:"transactionHash" gencodec:"required" rlp:"-"`
	// index of the transaction in the block
	TxIndex uint `json:"transactionIndex" rlp:"-"`
	// hash of the block in which the transaction was included
	BlockHash common.Hash `json:"blockHash" rlp:"-"`
	// timestamp of the block in which the transaction was included
	BlockTimestamp uint64 `json:"blockTimestamp" rlp:"-"`
	// index of the log in the block
	Index uint `json:"logIndex" rlp:"-"`

	// The Removed field is true if this log was reverted due to a chain reorganisation.
	// You must pay attention to this field if you receive logs through a filter query.
	Removed bool `json:"removed" rlp:"-"`
}

// LoggerBytes returns the account mixed into a bloom or log index.
// An address32 logger contributes its 32 bytes. An address20 logger contributes its 20 bytes.
func (l *Log) LoggerBytes() []byte {
	if l.Address32 != nil {
		return l.Address32.Bytes()
	}

	return l.Address.Bytes()
}

// DecodeRLP accepts the historical 20-byte logger and an address32 logger.
func (l *Log) DecodeRLP(s *rlp.Stream) error {
	blob, err := s.Raw()

	if err != nil {
		return err
	}

	var dec struct {
		Address []byte
		Topics  []common.Hash
		Data    []byte
	}

	if err := rlp.DecodeBytes(blob, &dec); err != nil {
		return err
	}

	if err := l.setLogger(dec.Address); err != nil {
		return err
	}

	l.Topics = dec.Topics
	l.Data = dec.Data
	return nil
}

// EncodeRLP writes the consensus log. The address is 32 bytes for an address32 logger and 20 bytes for an address20 logger.
func (l *Log) EncodeRLP(w io.Writer) error {
	buf := rlp.NewEncoderBuffer(w)
	outer := buf.List()
	buf.WriteBytes(l.LoggerBytes())
	topics := buf.List()

	for _, topic := range l.Topics {
		buf.WriteBytes(topic[:])
	}

	buf.ListEnd(topics)
	buf.WriteBytes(l.Data)
	buf.ListEnd(outer)
	return buf.Flush()
}

// MarshalJSON encodes the log. The address field is 32 bytes for an address32 logger and 20 bytes for an address20 logger.
func (l Log) MarshalJSON() ([]byte, error) {
	type enc struct {
		Address        hexutil.Bytes  `json:"address" gencodec:"required"`
		Topics         []common.Hash  `json:"topics" gencodec:"required"`
		Data           hexutil.Bytes  `json:"data" gencodec:"required"`
		BlockNumber    hexutil.Uint64 `json:"blockNumber"`
		TxHash         common.Hash    `json:"transactionHash" gencodec:"required"`
		TxIndex        hexutil.Uint   `json:"transactionIndex"`
		BlockHash      common.Hash    `json:"blockHash"`
		BlockTimestamp hexutil.Uint64 `json:"blockTimestamp"`
		Index          hexutil.Uint   `json:"logIndex"`
		Removed        bool           `json:"removed"`
	}

	return json.Marshal(&enc{
		Address:        l.LoggerBytes(),
		Topics:         l.Topics,
		Data:           l.Data,
		BlockNumber:    hexutil.Uint64(l.BlockNumber),
		TxHash:         l.TxHash,
		TxIndex:        hexutil.Uint(l.TxIndex),
		BlockHash:      l.BlockHash,
		BlockTimestamp: hexutil.Uint64(l.BlockTimestamp),
		Index:          hexutil.Uint(l.Index),
		Removed:        l.Removed,
	})
}

// UnmarshalJSON decodes the log. The address field may be 20 or 32 bytes.
func (l *Log) UnmarshalJSON(input []byte) error {
	type dec struct {
		Address        *hexutil.Bytes  `json:"address" gencodec:"required"`
		Topics         []common.Hash   `json:"topics" gencodec:"required"`
		Data           *hexutil.Bytes  `json:"data" gencodec:"required"`
		BlockNumber    *hexutil.Uint64 `json:"blockNumber"`
		TxHash         *common.Hash    `json:"transactionHash" gencodec:"required"`
		TxIndex        *hexutil.Uint   `json:"transactionIndex"`
		BlockHash      *common.Hash    `json:"blockHash"`
		BlockTimestamp *hexutil.Uint64 `json:"blockTimestamp"`
		Index          *hexutil.Uint   `json:"logIndex"`
		Removed        *bool           `json:"removed"`
	}

	var parsed dec

	if err := json.Unmarshal(input, &parsed); err != nil {
		return err
	}

	if parsed.Address == nil {
		return errors.New("missing required field 'address' for Log")
	}

	if err := l.setLogger(*parsed.Address); err != nil {
		return err
	}

	if parsed.Topics == nil {
		return errors.New("missing required field 'topics' for Log")
	}

	l.Topics = parsed.Topics

	if parsed.Data == nil {
		return errors.New("missing required field 'data' for Log")
	}

	l.Data = *parsed.Data

	if parsed.BlockNumber != nil {
		l.BlockNumber = uint64(*parsed.BlockNumber)
	}

	if parsed.TxHash == nil {
		return errors.New("missing required field 'transactionHash' for Log")
	}

	l.TxHash = *parsed.TxHash

	if parsed.TxIndex != nil {
		l.TxIndex = uint(*parsed.TxIndex)
	}

	if parsed.BlockHash != nil {
		l.BlockHash = *parsed.BlockHash
	}

	if parsed.BlockTimestamp != nil {
		l.BlockTimestamp = uint64(*parsed.BlockTimestamp)
	}

	if parsed.Index != nil {
		l.Index = uint(*parsed.Index)
	}

	if parsed.Removed != nil {
		l.Removed = *parsed.Removed
	}

	return nil
}

// setLogger stores a 20-byte or 32-byte logger on the log.
// A 32-byte value in the address20 subspace is rejected: log encoding uses the length, and an address32 cannot occupy that subspace.
func (l *Log) setLogger(raw []byte) error {
	if len(raw) == common.Address32Length {
		addr, err := common.NewAddress32(raw)

		if err != nil {
			return err
		}

		l.Address = common.Address{}
		l.Address32 = &addr
		return nil
	}

	if len(raw) != common.AddressLength {
		return fmt.Errorf("log address must be 20 or 32 bytes, have %d", len(raw))
	}

	l.Address = common.BytesToAddress(raw)
	l.Address32 = nil
	return nil
}

// Loggers is the set of address20 and address32 accounts selected as log emitters.
type Loggers struct {
	// Addresses restricts the set to these address20 accounts.
	Addresses []common.Address
	// Addresses32 restricts the set to these address32 accounts.
	Addresses32 []common.Address32
}

// Listed reports whether the set names at least one account.
func (l Loggers) Listed() bool {
	return len(l.Addresses) > 0 || len(l.Addresses32) > 0
}
